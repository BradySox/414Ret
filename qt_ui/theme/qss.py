"""Generate the Qt stylesheet from the design tokens.

Replaces the hand-maintained ``style-dcs.css``, in which every colour was a
literal and the same grey appeared under several spellings. Every rule below is
derived from :mod:`qt_ui.theme.tokens`, so a palette change is one edit.

This is a faithful superset of the sheet it replaces: every widget selector and
every ``style="..."`` property hook the old sheet carried is still styled, so no
screen loses its look. It additionally styles widgets the old sheet never
covered — scrollbar handles, radio buttons, sliders, tooltips, the status bar,
splitter handles, list/table rows and focus states — which previously fell
through to the platform default and read as unthemed.
"""

