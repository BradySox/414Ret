def task_chip_colors() -> dict[str, str]:
    """Flight-task name -> chip colour, for tests and any non-QSS consumer."""
    colors: dict[str, str] = {}
    for names, color in _TASK_GROUPS:
        for name in names:
            colors[name] = color
    return colors


def _task_chips(p: Palette, s: Scale) -> str:
    rules = []
    for names, color in _TASK_GROUPS:
        selector = ", ".join(f'QLabel[style="{name}"]' for name in names)
        rules.append(
            f"{selector} {{\n"
            f"    background-color: {color};\n"
            f"    color: {p.text};\n"
            f"    border: none;\n"
            f"    border-radius: {s.radius_sm}px;\n"
            f"    padding: {s.space_1}px {s.space_3}px;\n"
            f"    font-weight: 600;\n"
            f"}}"
        )
    return "\n".join(rules)


def build_stylesheet(p: Palette = RETRIBUTION_DARK, s: Scale = SCALE) -> str:
    """Build the complete application stylesheet."""
    return "\n".join(
        [
            _base(p, s),
            _chrome(p, s),
            _buttons(p, s),
            _labels(p, s),
            _task_chips(p, s),
            _containers(p, s),
            _inputs(p, s),
            _views(p, s),
            _finances(p, s),
            _panel_overrides(p, s),
            _legacy_classes(p, s),
        ]
    )


