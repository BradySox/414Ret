# Trimmed from a real "atmosx-cli metar LCLK --save" run: comments, the trailing
# "-- end of vdata" markers and the two top-level assignments the reader must cope with.
PRESET = """\
-- Weather preset: ATX - LCLK METAR
-- Generated by ATMOS-X CLI: 2026-08-19 11:30:07

vdata = {
    name = "ATX - LCLK METAR",
    atmosphere_type = 0,
    groundTurbulence = 0.0000,
    enable_dust = false,
    dust_density = 0,
    qnh = 758,
    season = {
        temperature = 31.0,
    },
    visibility = {
        distance = 80000,
    },
    wind = {
        atGround = { speed = 3.60, dir = 350, },
        at2000 = { speed = 4.32, dir = 350, },
        at8000 = { speed = 5.40, dir = 350, },
    },
    clouds = {
        preset = "none",
        thickness = 0,
        density = 0,
        base = 764,
        iprecptns = 0,
    },
    fog2 = {
        mode = 1,
        manual = {
        },
    },
} -- end of vdata
dtime = {
    date = {
        Year = 2026,
        Day = 19,
        Month = 8,
    },
    start_time = 43200,
} -- end of dtime
"""


def test_reads_both_top_level_blocks() -> None:
    """dtime is parsed and then ignored -- the mission always keeps its own clock."""
    parsed = parse_preset(PRESET)
    assert set(parsed) == {"vdata", "dtime"}
    assert parsed["vdata"]["qnh"] == 758
    assert parsed["vdata"]["clouds"]["preset"] == "none"
    assert parsed["vdata"]["enable_dust"] is False
    assert parsed["vdata"]["wind"]["atGround"] == {"speed": 3.6, "dir": 350}
    assert parsed["vdata"]["fog2"]["manual"] == {}


def test_a_malformed_preset_is_an_error_not_a_wrong_answer() -> None:
    with pytest.raises(PresetParseError):
        parse_preset("vdata = { qnh = ")


def test_the_observation_lands_on_the_mission() -> None:
    weather = Weather("Syria")
    apply_weather(weather, parse_preset(PRESET)["vdata"])
    assert weather.qnh == 758
    assert weather.season_temperature == 31.0
    assert weather.visibility_distance == 80000
    assert weather.wind_at_ground.speed == 3.6
    assert weather.wind_at_8000.direction == 350
    # A clear METAR: preset "none" means no preset, not a preset called "none".
    assert weather.clouds_preset is None
    assert weather.clouds_base == 0


def test_the_mission_can_still_be_written_out() -> None:
    """The regression that matters: DCS reads .name off the preset and validates the
    base against it, so a preset key left as a bare string kills mission generation."""
    for key, base in (("none", 764), ("Preset10", 2000)):
        vdata = parse_preset(PRESET)["vdata"]
        vdata["clouds"] = {
            "preset": key,
            "base": base,
            "thickness": 0,
            "density": 0,
            "iprecptns": 0,
        }
        weather = Weather("Syria")
        apply_weather(weather, vdata)
        assert isinstance(weather.dict(), dict)


def test_a_ceiling_outside_the_presets_range_is_clamped_not_fatal() -> None:
    """DCS refuses the mission outright; a METAR ceiling near the edge is common."""
    preset = CLOUD_PRESETS["Preset10"].value
    vdata = parse_preset(PRESET)["vdata"]
    vdata["clouds"] = {
        "preset": "Preset10",
        "base": 1,
        "thickness": 0,
        "density": 0,
        "iprecptns": 0,
    }
    weather = Weather("Syria")
    apply_weather(weather, vdata)
    assert weather.clouds_base >= preset.min_base
    assert isinstance(weather.dict(), dict)


def test_fields_a_metar_says_nothing_about_are_left_alone() -> None:
    """The preset is not a whole weather definition; what it omits the campaign keeps."""
    weather = Weather("Syria")
    halo, cyclones = weather.halo, weather.cyclones
    weather.type_weather = 2
    apply_weather(weather, parse_preset(PRESET)["vdata"])
    assert weather.halo is halo
    assert weather.cyclones is cyclones
    assert weather.type_weather == 2


