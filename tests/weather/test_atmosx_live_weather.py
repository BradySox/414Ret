def test_the_bases_are_read_before_the_coalitions_are_wired() -> None:
    """`Game.__init__` generates conditions before `ControlPoint.finish_init` runs.

    Reading `captured` there raised and took New Game down with it, so the preference
    list comes from `starting_coalition` instead.
    """

    class NotYetInitialized:
        def __init__(self, name: str, blue: bool) -> None:
            self.name = name
            self.starting_coalition = SimpleNamespace(is_blue=blue)

        @property
        def captured(self) -> Any:
            raise RuntimeError("ControlPoint not fully initialized: coalition not set")

    theater = SimpleNamespace(
        controlpoints=[
            NotYetInitialized("Incirlik", True),
            NotYetInitialized("Hama", False),
        ]
    )
    assert preferred_airfields(theater) == ["Incirlik"]


def test_a_theater_with_no_control_points_asks_for_nothing() -> None:
    assert preferred_airfields(SimpleNamespace()) == []


def test_a_failure_inside_the_lookup_never_stops_the_turn() -> None:
    """The module header promises this. Until New Game crashed it was not enforced."""

    class Exploding:
        @property
        def atmosx_live_weather(self) -> bool:
            raise RuntimeError("the CLI, the network, or a half-built theater")

    assert live_weather_for(SimpleNamespace(), Exploding()) is None


# --- the settings only apply when they can do something -------------------------


def test_the_atmosx_settings_are_gated_on_that_pack_being_selected() -> None:
    """A knob that quietly does nothing is worse than one visibly greyed out.

    The fork gates dependants with ``enabled_when`` (greys the control and its
    label, live across pages via SettingsDependencyHub) rather than upstream's
    separate hiding mechanism, so this pins the dependency rather than a predicate.
    """
    from game.settings import Settings
    from game.settings.settings import CloudPresetPack, MISSION_GENERATION_PAGE

    guarded = {
        name: description
        for name, description in Settings.fields(MISSION_GENERATION_PAGE, "Weather")
        if name.startswith("atmosx_")
    }
    assert set(guarded) == {
        "atmosx_live_weather",
        "atmosx_cli_path",
        "atmosx_metar_station",
    }
    for description in guarded.values():
        assert description.enabled_when == (
            "cloud_preset_pack",
            CloudPresetPack.ATMOSX,
        )


def test_the_pack_and_its_knobs_are_laid_out_together() -> None:
    """A dependency the player cannot see next to its master reads as broken."""
    from game.settings.settings import FIELD_LAYOUT, MISSION_GENERATION_PAGE

    for name in (
        "cloud_preset_pack",
        "atmosx_live_weather",
        "atmosx_cli_path",
        "atmosx_metar_station",
    ):
        assert FIELD_LAYOUT[name] == (MISSION_GENERATION_PAGE, "Weather")


# --- the observation as the turn's own weather -----------------------------------


def test_the_observation_becomes_the_weather_the_game_reads() -> None:
    """The kneeboard, the active runway and the carrier all read this, not the .miz."""
    weather = LiveWeather("LCLK", parse_preset(PRESET)["vdata"])

    assert round(weather.atmospheric.qnh.mm_hg) == 758
    assert weather.atmospheric.temperature_celsius == 31.0
    assert weather.atmospheric.turbulence_per_10cm == 0.0
    assert weather.wind.at_0m.direction == 350
    assert weather.wind.at_0m.speed == 3.6
    assert weather.wind.at_8000m.speed == 5.4
    # "none" with nothing to draw is a clear sky, which is what the rest of the game
    # understands by no clouds.
    assert weather.clouds is None
    assert weather.fog is None
    assert weather.archetype.id == "clear"


def test_a_named_preset_survives_into_the_model() -> None:
    vdata = parse_preset(PRESET)["vdata"]
    vdata["clouds"] = {
        "preset": "Preset10",
        "base": 2000,
        "thickness": 1200,
        "density": 6,
        "iprecptns": 1,
    }
    weather = LiveWeather("LCLK", vdata)
    assert weather.clouds is not None
    assert weather.clouds.preset is not None
    assert weather.clouds.preset.name == CLOUD_PRESETS["Preset10"].value.name
    assert weather.clouds.base == 2000
    assert weather.clouds.precipitation is PydcsWeather.Preceptions.Rain
    assert weather.archetype.id == "raining"


def test_a_preset_this_dcs_does_not_have_is_not_fatal() -> None:
    """A pack the player has not installed must not take the campaign down with it."""
    vdata = parse_preset(PRESET)["vdata"]
    vdata["clouds"] = {
        "preset": "Preset9999",
        "base": 900,
        "thickness": 0,
        "density": 4,
    }
    weather = LiveWeather("LCLK", vdata)
    assert weather.clouds is not None and weather.clouds.preset is None
    assert weather.clouds.base == 900


def test_the_mission_still_gets_what_the_model_cannot_hold() -> None:
    """visibility distance and dust have nowhere to live but the mission itself."""
    vdata = parse_preset(PRESET)["vdata"]
    vdata["visibility"] = {"distance": 4200}
    vdata["enable_dust"] = True
    vdata["dust_density"] = 3
    mission_weather = Weather("Syria")
    apply_weather(mission_weather, LiveWeather("LCLK", vdata).vdata)
    assert mission_weather.visibility_distance == 4200
    assert mission_weather.enable_dust is True
    assert mission_weather.dust_density == 3


