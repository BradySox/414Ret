# --- the fork couplings ----------------------------------------------------------
#
# Upstream #927 hooks a single call site (`Conditions.generate`) because upstream
# re-rolls the weather from scratch every turn. The fork does not: §47 marches one
# clock and evolves the sky from the previous turn, §67 reads that sky to plan. All
# three couplings are pinned here -- each was a real defect in the straight port.


def _seasonal() -> Any:
    from game.theater.seasonalconditions import (
        Season,
        SeasonalConditions,
        WeatherTypeChances,
    )

    chances = WeatherTypeChances(
        thunderstorm=1.0, raining=1.0, cloudy=1.0, clear_skies=1.0
    )
    return SeasonalConditions(
        summer_avg_pressure=30.0,
        winter_avg_pressure=30.0,
        summer_avg_temperature=25.0,
        winter_avg_temperature=5.0,
        temperature_day_night_difference=10.0,
        high_avg_yearly_turbulence_per_10cm=1.0,
        low_avg_yearly_turbulence_per_10cm=0.1,
        solar_noon_turbulence_per_10cm=0.5,
        midnight_turbulence_per_10cm=0.1,
        weather_type_chances={season: chances for season in Season},
    )


def _theater() -> Any:
    from game.theater.daytimemap import DaytimeMap

    daytime = DaytimeMap(
        dawn=(datetime(2020, 1, 1, 6).time(), datetime(2020, 1, 1, 8).time()),
        day=(datetime(2020, 1, 1, 8).time(), datetime(2020, 1, 1, 16).time()),
        dusk=(datetime(2020, 1, 1, 16).time(), datetime(2020, 1, 1, 20).time()),
        night=(datetime(2020, 1, 1, 20).time(), datetime(2020, 1, 1, 23).time()),
    )
    return SimpleNamespace(seasonal_conditions=_seasonal(), daytime_map=daytime)


def _stormy_live_weather() -> LiveWeather:
    vdata = parse_preset(PRESET)["vdata"]
    vdata["clouds"] = {
        "preset": "Preset10",
        "base": 2000,
        "thickness": 1200,
        "density": 9,
        "iprecptns": 2,
    }
    return LiveWeather("LCLK", vdata)


def test_the_turn_after_a_real_observation_still_generates() -> None:
    """§47's ladder is a list of the four generated classes; LiveWeather is on none
    of them, so taking its class raised StopIteration on the next turn advance."""
    from game.weather.conditions import Conditions

    theater = _theater()
    previous = Conditions(
        time_of_day=TimeOfDay.Day,
        start_time=datetime(2020, 6, 15, 8, 0),
        weather=_stormy_live_weather(),
    )
    advanced = Conditions.advance(previous, theater)
    assert advanced.weather is not None
    assert advanced.start_time > previous.start_time


def test_the_next_turn_evolves_from_the_sky_that_was_actually_flown() -> None:
    """Not merely "does not crash": a live thunderstorm has to bias the next turn
    the way a generated one would, or the observation breaks the weather's memory."""
    from game.weather.conditions import Conditions
    from game.weather.weather import Thunderstorm

    assert Conditions._ladder_type(_stormy_live_weather()) is Thunderstorm


def test_live_weather_reaches_every_turn_not_only_the_first(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """Turns 2+ come through `advance`, so hooking only `generate` would leave the
    feature working once and never again."""
    import game.weather.conditions as conditions_module
    from game.weather.conditions import Conditions

    observed = _stormy_live_weather()
    monkeypatch.setattr(
        conditions_module, "live_weather_for", lambda theater, settings: observed
    )
    previous = Conditions(
        time_of_day=TimeOfDay.Day,
        start_time=datetime(2020, 6, 15, 8, 0),
        weather=observed,
    )
    advanced = Conditions.advance(previous, _theater(), object())  # type: ignore[arg-type]
    assert advanced.weather is observed
    # Without settings there is nothing to ask, and the generated sky stands.
    assert Conditions.advance(previous, _theater()).weather is not observed


def test_the_weather_aware_planner_sees_a_live_storm() -> None:
    """§67 tested isinstance(Raining, Thunderstorm); a LiveWeather is neither, so a
    real thunderstorm read as clear -- auto-recon flew and low-level attack stayed."""
    from game.fourteenth import weather_planning

    game = SimpleNamespace(
        settings=SimpleNamespace(weather_aware_planning=True),
        conditions=SimpleNamespace(weather=_stormy_live_weather()),
    )
    assert weather_planning.storm(game)  # type: ignore[arg-type]
    assert weather_planning.poor_visibility_weather(game)  # type: ignore[arg-type]
    assert weather_planning.recon_suppressed(game)  # type: ignore[arg-type]


def test_a_clear_observation_leaves_the_planner_alone() -> None:
    from game.fourteenth import weather_planning

    game = SimpleNamespace(
        settings=SimpleNamespace(weather_aware_planning=True),
        conditions=SimpleNamespace(
            weather=LiveWeather("LCLK", parse_preset(PRESET)["vdata"])
        ),
    )
    assert not weather_planning.storm(game)  # type: ignore[arg-type]
    assert not weather_planning.recon_suppressed(game)  # type: ignore[arg-type]
